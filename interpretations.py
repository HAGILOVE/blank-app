def element_analysis(counts: dict, day_master_element: str) -> str:
    """오행 분포를 보고 강약·균형을 해설."""
    total = sum(counts.values())
    if total == 0:
        return "오행 정보가 부족합니다."

    sorted_elems = sorted(counts.items(), key=lambda x: -x[1])
    strongest = sorted_elems[0][0]
    weakest = sorted_elems[-1][0]
    lacking = [k for k, v in counts.items() if v == 0]
    dm_count = counts.get(day_master_element, 0)

    msg = []
    if dm_count >= 4:
        msg.append(
            f"일간 **{day_master_element}**의 기운이 매우 강합니다(신강). "
            "자신감과 추진력이 넘치나, 독선과 고집을 다스리는 절제가 필요합니다."
        )
    elif dm_count >= 3:
        msg.append(
            f"일간 **{day_master_element}**가 충분히 강합니다(중강). "
            "주체적이고 활동적이며, 자신의 길을 개척하는 힘이 있습니다."
        )
    elif dm_count <= 1:
        msg.append(
            f"일간 **{day_master_element}**의 기운이 약합니다(신약). "
            "신중하고 사려 깊으나, 의존하기보다 자기를 보강하는 노력이 필요합니다."
        )
    else:
        msg.append(
            f"일간 **{day_master_element}**가 적절합니다(중화). "
            "안정적이며 융통성 있게 환경에 적응하는 균형형 사주입니다."
        )

    msg.append(
        f"전체적으로 **{strongest}** 기운이 가장 강하고, **{weakest}** 기운이 가장 약합니다."
    )
    if lacking:
        lacking_str = ", ".join(f"**{l}**" for l in lacking)
        msg.append(
            f"부족한 오행: {lacking_str}. 부족한 오행은 색상·방위·취미·인연으로 보완할 수 있습니다."
        )
    else:
        msg.append("오행이 모두 갖춰져 균형 잡힌 사주입니다. 큰 결함이 없는 안정형.")
    return "  \n".join(msg)


